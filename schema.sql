-- TANKS / WASSERRESERVOIRS
CREATE TABLE tanks (
    tank_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    kapazitaet_liter NUMBER(8,2) NOT NULL,
    standort VARCHAR2(100),
    erstellt_am TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- REIHEN / BEPFLANZUNG
CREATE TABLE reihen (
    reihe_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bezeichnung VARCHAR2(100) NOT NULL,
    pflanzen_art VARCHAR2(100),
    ziel_bodenfeuchte_prozent NUMBER(5,2),
    erstellt_am TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- SENSOREN
CREATE TABLE sensoren (
    sensor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    typ VARCHAR2(50) NOT NULL,
    pin_gpio NUMBER(3),
    tank_id NUMBER CONSTRAINT fk_sensor_tank REFERENCES tanks(tank_id) ON DELETE SET NULL,
    reihe_id NUMBER CONSTRAINT fk_sensor_reihe REFERENCES reihen(reihe_id) ON DELETE SET NULL
);

-- AKTOREN / PUMPEN / VENTILE
CREATE TABLE aktoren (
    aktor_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    typ VARCHAR2(50) NOT NULL,
    pin_gpio NUMBER(3) NOT NULL,
    status VARCHAR2(20) DEFAULT 'AUS',
    reihe_id NUMBER CONSTRAINT fk_aktor_reihe REFERENCES reihen(reihe_id) ON DELETE SET NULL
);

-- MESSWERTE HISTORIE
CREATE TABLE messwerte (
    messwert_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id NUMBER NOT NULL CONSTRAINT fk_messwert_sensor REFERENCES sensoren(sensor_id) ON DELETE CASCADE,
    wert NUMBER(10,2) NOT NULL,
    einheit VARCHAR2(20),
    gemessen_am TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- BEWÄSSERUNGSLOGS
CREATE TABLE bewaesserung_log (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aktor_id NUMBER CONSTRAINT fk_log_aktor REFERENCES aktoren(aktor_id) ON DELETE SET NULL,
    dauer_sekunden NUMBER(6) NOT NULL,
    ausgeloest_durch VARCHAR2(50) DEFAULT 'CAMUNDA',
    gestartet_am TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
